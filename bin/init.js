#!/usr/bin/env node
/**
 * walrus-agent-stack init — first-run setup.
 *
 * Generates a fresh testnet Ed25519 keypair, requests faucet funds, and writes
 * ~/.walrus-agent-stack/config.env + session.json so the MCP server has the
 * environment it needs on first start.
 *
 * Idempotent: if config.env already exists we exit 0 without touching it.
 */
import { Ed25519Keypair } from '@mysten/sui/keypairs/ed25519';
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const HOME = homedir();
const CONFIG_DIR = join(HOME, '.walrus-agent-stack');
const CONFIG_FILE = join(CONFIG_DIR, 'config.env');
const SESSION_FILE = join(CONFIG_DIR, 'session.json');

const FAUCET_V2 = 'https://faucet.testnet.sui.io/v2/gas';
const FAUCET_V1 = 'https://faucet.testnet.sui.io/gas';

// Real testnet Seal key-server object IDs (mirrors sui-stack-messaging defaults).
// Users may override SEAL_SERVERS in config.env if Mysten rotates these.
const DEFAULT_SEAL_SERVERS = [
  '0x73d05d62c18d9374e3ea529e8e0ed6161da1a141a94d3f76ae3fe4e99356db75',
  '0xf5d14a81a982144ae441cd7d64b09027f116a468bd36e7eca494f750591623c8',
].join(',');

async function requestFaucet(recipient) {
  const body = JSON.stringify({ FixedAmountRequest: { recipient } });
  const endpoints = [FAUCET_V2, FAUCET_V1];
  for (const url of endpoints) {
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body,
      });
      if (res.ok) {
        console.log(`Faucet OK via ${url} (status ${res.status})`);
        return;
      }
      if (res.status === 404) {
        console.log(`Faucet ${url} returned 404; trying next endpoint`);
        continue;
      }
      const text = await res.text().catch(() => '<no body>');
      console.log(`Faucet ${url} returned ${res.status}: ${text}`);
      return;
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      console.log(`Faucet ${url} threw: ${msg}; trying next endpoint`);
    }
  }
  console.log('Faucet request failed on all known endpoints (testnet may be rate-limiting).');
}

async function main() {
  mkdirSync(CONFIG_DIR, { recursive: true });

  if (existsSync(CONFIG_FILE)) {
    console.log(`Config already exists at ${CONFIG_FILE}.`);
    console.log('Delete it first if you want to regenerate.');
    process.exit(0);
  }

  const kp = Ed25519Keypair.generate();
  const address = kp.toSuiAddress();
  const privateKey = kp.getSecretKey(); // bech32 "suiprivkey1..."

  console.log(`Generated wallet: ${address}`);

  console.log('Requesting testnet SUI from faucet...');
  await requestFaucet(address);

  const config = [
    '# walrus-agent-stack config — generated by `npx walrus-agent-stack`.',
    '# Edit any value to override the defaults.',
    `SUI_PRIVATE_KEY=${privateKey}`,
    'SUI_NETWORK=testnet',
    '# No public testnet relayer yet — run a local sui-stack-messaging relayer or set this.',
    'RELAYER_URL=http://localhost:3000',
    '# Default Mysten testnet Seal key servers; override if these rotate.',
    `SEAL_SERVERS=${DEFAULT_SEAL_SERVERS}`,
    'SUI_RPC_URLS=https://fullnode.testnet.sui.io:443',
    '',
  ].join('\n');
  writeFileSync(CONFIG_FILE, config);
  writeFileSync(SESSION_FILE, '{}\n');

  console.log(`\nConfig written to ${CONFIG_FILE}.`);
  console.log(`Session state initialised at ${SESSION_FILE}.`);
  console.log('\nNext steps:');
  console.log('  1. Confirm RELAYER_URL points at a running sui-stack-messaging relayer.');
  console.log('  2. Run `/plugin install walrus-agent-stack` inside Claude Code.');
  console.log('  3. Try `/agent-channel new "test"` to create your first channel.');
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
